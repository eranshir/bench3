def polyglot(lang: str, count: int, seed: int) -> list[Path]:
    repo = CACHE / "polyglot-benchmark"
    if not repo.exists():
        sh(["git", "clone", "-q", POLYGLOT_REPO, str(repo)])
    commit = sh(["git", "rev-parse", "HEAD"], cwd=repo).stdout.strip()
    root = repo / lang / "exercises" / "practice"
    names = sorted(p.name for p in root.iterdir() if p.is_dir())
    picks = random.Random("%s:%d" % (lang, seed)).sample(names, count)
    made = []
    for name in picks:
        ex = root / name
        cfg = json.loads((ex / ".meta" / "config.json").read_text())
        hidden = set(cfg["files"]["test"])
        helper_dirs = [d for d in ("test",) if (ex / d).is_dir()]  # cpp ships catch.hpp under test/
        write = {rel: (ex / rel).read_text() for rel in hidden}
        for d in helper_dirs:
            for f in (ex / d).rglob("*"):
                if f.is_file():
                    write[str(f.relative_to(ex))] = f.read_text()
        docs = "\n\n".join((ex / ".docs" / n).read_text() for n in ("instructions.md", "instructions.append.md")
                           if (ex / ".docs" / n).exists())
        sol = cfg["files"]["solution"]
        prompt = (docs + "\n\n# Your task\n\nImplement this exercise in %s by editing %s in the current directory. "
                  "Keep the existing public names. The tests are hidden; they will be run after you finish."
                  % (lang, ", ".join(sol)))

        def fixture(task, ex=ex, skip=hidden, helper_dirs=helper_dirs):
            for f in ex.rglob("*"):
                rel = f.relative_to(ex)
                if f.is_file() and not rel.parts[0].startswith(".") and str(rel) not in skip \
                        and rel.parts[0] not in helper_dirs:
                    (task / rel).parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(f, task / rel)

        reference = {}
        for sol_rel, ex_rel in zip(sol, cfg["files"]["example"]):
            reference[sol_rel] = (ex / ex_rel).read_text()
        spec = {"kind": "commands", "write": write, "cmds": POLYGLOT_CMDS[lang](cfg), "timeout": 600,
                "dir_name": name if lang == "cpp" else None}
        meta = {"source": "Aider-AI/polyglot-benchmark", "source_commit": commit, "upstream_id": "%s/%s" % (lang, name),
                "licence": "no licence file in the repository; exercises originate from Exercism tracks",
                "difficulty_label": None, "imported_at": datetime.now(timezone.utc).isoformat()}
        made.append(write_task("polyglot", "%s-%s" % (lang, name), prompt, fixture, spec, reference, meta))
    return made


# --- SWE-bench Verified --------------------------------------------------------------------------

def swe_rows() -> list[dict]:
    cache = CACHE / "swe_verified.json"
    if not cache.exists():
        rows = []
        for off in range(0, 500, 100):
            rows += [r["row"] for r in json.load(urllib.request.urlopen(SWE_ROWS % off))["rows"]]
        CACHE.mkdir(parents=True, exist_ok=True)
        cache.write_text(json.dumps(rows))
    return json.loads(cache.read_text())


def swe_python() -> Path:
    """One Python 3.9 environment (the official harness version for sympy) with pytest and mpmath."""
    venv = CACHE / "swe-py39"
    if not (venv / "bin" / "python").exists():
        sh(["uv", "venv", "--python", "3.9", str(venv)])
        sh(["uv", "pip", "install", "--python", str(venv / "bin" / "python"), "pytest==7.4.4", "mpmath==1.3.0"])
    return venv / "bin" / "python"


def swe(instances: list[str]) -> list[Path]:
    rows = {r["instance_id"]: r for r in swe_rows()}
    python = swe_python()
    made = []
    for iid in instances:
        row = rows[iid]
        repo = CACHE / "repos" / row["repo"].replace("/", "__")
        if not repo.exists():
            sh(["git", "clone", "-q", "https://github.com/%s.git" % row["repo"], str(repo)])
        test_files = sorted(set(re.findall(r"^\+\+\+ b/(\S+)", row["test_patch"], re.M)))

        def fixture(task, repo=repo, commit=row["base_commit"]):
            archive = subprocess.run(["git", "archive", commit], cwd=repo, check=True, capture_output=True).stdout
            subprocess.run(["tar", "-x", "-C", str(task)], input=archive, check=True)

        prompt = (row["problem_statement"].strip() + "\n\n# Your task\n\nThe repository is in the current directory. "
                  "Resolve the issue above by editing the source code; do not edit or add tests. A Python with the "
                  "project's test dependencies is at %s. Hidden tests will be run after you finish." % python)
        f2p, p2p = json.loads(row["FAIL_TO_PASS"]), json.loads(row["PASS_TO_PASS"])
        spec = {"kind": "pytest-names", "test_patch": row["test_patch"], "test_files": test_files,
                "python": str(python), "must_pass": f2p + p2p, "timeout": 1800}
        meta = {"source": "princeton-nlp/SWE-bench_Verified", "upstream_id": iid, "repo": row["repo"],
                "base_commit": row["base_commit"], "version": row["version"], "difficulty_label": row["difficulty"],
                "licence": "task text and patches from %s under that project's licence" % row["repo"],
                "reference_patch": True, "fail_to_pass": f2p, "imported_at": datetime.now(timezone.utc).isoformat()}
        task = write_task("swe-verified", iid, prompt, fixture, spec, {"gold.patch": row["patch"]}, meta)
        # Keep only the pass-to-pass tests that actually pass with the gold patch in this environment.
        spec["must_pass"] = f2p + [n for n in p2p if n in gold_passing(task, test_files, python)]
        (task / "hidden_test.py").write_text(HIDDEN_TEST.replace("{spec}", base64.b64encode(json.dumps(spec).encode()).decode()))
        made.append(task)
    return made


def gold_passing(task: Path, test_files: list[str], python: Path) -> set[str]:
    work = Path(tempfile.mkdtemp(prefix="bench3-gold-")) / "work"
    shutil.copytree(task, work, ignore=shutil.ignore_patterns("reference", "PROMPT.txt", ".import.json", "hidden_test.py"))
    spec = json.loads(base64.b64decode(re.search(r'b64decode\("([^"]+)"\)', (task / "hidden_test.py").read_text()).group(1)))
    for patch in ((task / "reference" / "gold.patch").read_text(), spec["test_patch"]):
        p = work / "_p.patch"; p.write_text(patch)
        sh(["git", "apply", "--whitespace=nowarn", str(p)], cwd=work); p.unlink()
    xml = work.parent / "gold.xml"
    subprocess.run([str(python), "-m", "pytest", "-q", "-p", "no:cacheprovider", "--junitxml", str(xml), *test_files],
                   cwd=work, capture_output=True, text=True, timeout=3600)
    import xml.etree.ElementTree as ET
    names = {c.get("name").split("[")[0] for c in ET.parse(xml).iter("testcase")
             if not any(ch.tag in ("failure", "error", "skipped") for ch in c)} if xml.exists() else set()
    shutil.rmtree(work.parent, ignore_errors=True)
    return names


def swe_sample(repo: str, per: int, seed: int) -> list[str]:
    skip = excluded()
    rows = [r for r in swe_rows() if r["repo"] == repo and "swe-bench:" + r["instance_id"] not in skip]
    picks = []
    for band in ("<15 min fix", "15 min - 1 hour", "1-4 hours"):
        pool = sorted(r["instance_id"] for r in rows if r["difficulty"] == band)
        picks += random.Random("%s:%s:%d" % (repo, band, seed)).sample(pool, min(per, len(pool)))
    return picks


# --- Harbor code-contests ------------------------------------------------------------------------

def hf_file(path: str) -> str:
    url = "https://huggingface.co/datasets/%s/resolve/main/%s" % (HARBOR, path)
    return urllib.request.urlopen(url).read().decode()


def codecontests(per_band: int, seed: int) -> list[Path]:
    skip = excluded()
    listing = json.load(urllib.request.urlopen(
        "https://huggingface.co/api/datasets/%s/tree/main/datasets/code-contests" % HARBOR))
    names = sorted(p["path"].rsplit("/", 1)[-1] for p in listing)
    names = [n for n in names if "term:code-contests/" + n not in skip]
    rng = random.Random("code-contests:%d" % seed)
    rng.shuffle(names)
    bands = {"<1200": [], "1200-1799": [], ">=1800": []}
    made = []
    for name in names:
        if all(len(v) >= per_band for v in bands.values()):
            break
        text = hf_file("datasets/code-contests/%s/instruction.md" % name)
        m = re.search(r"\*\*Rating\*\*: (\d+)", text)
        rating = int(m.group(1)) if m else 0
        if rating <= 0:
            continue
        band = "<1200" if rating < 1200 else "1200-1799" if rating < 1800 else ">=1800"
        if len(bands[band]) >= per_band:
            continue
        data = json.loads(hf_file("datasets/code-contests/%s/tests/test_data.json" % name))
        bands[band].append(name)
        prompt = text.replace("/app/solution.py", "solution.py").replace(
            "## Test Cases\nThe solution will be validated against multiple test cases.",
            "## Test Cases\nHidden test cases will be run against solution.py after you finish.")
        spec = {"kind": "stdio", "solution": "solution.py", "timeout": 10,
                "cases": list(zip(data["inputs"], data["outputs"]))}
        meta = {"source": HARBOR, "upstream_id": "code-contests/" + name, "rating": rating,
                "difficulty_label": band, "licence": "apache-2.0 (dataset card)",
                "note": "upstream test files carry the Terminal-Bench canary; keep scores out of training data",
                "imported_at": datetime.now(timezone.utc).isoformat()}
        made.append(write_task("code-contests", name, prompt, lambda task: None, spec, {}, meta))
    return made


