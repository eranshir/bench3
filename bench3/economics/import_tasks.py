def sh(cmd, cwd=None, **kw):
    return subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True, **kw)


def excluded() -> set[str]:
    return {l.strip() for l in EXCLUDE_FILE.read_text().splitlines() if l.strip()} if EXCLUDE_FILE.exists() else set()


def write_task(family: str, tid: str, prompt: str, fixture_from, spec: dict, reference: dict[str, str],
               meta: dict) -> Path:
    task = TASKS / family / tid
    if task.exists():
        shutil.rmtree(task)
    task.mkdir(parents=True)
    fixture_from(task)
    (task / "PROMPT.txt").write_text(prompt)
    (task / "hidden_test.py").write_text(HIDDEN_TEST.replace("{spec}", base64.b64encode(json.dumps(spec).encode()).decode()))
    ref = task / "reference"
    for rel, text in reference.items():
        (ref / rel).parent.mkdir(parents=True, exist_ok=True)
        (ref / rel).write_text(text)
    (task / ".import.json").write_text(json.dumps(meta, indent=1))
    return task


def grade_tree(task: Path, apply_reference: bool) -> tuple[bool, str]:
    """Copy the task as the runner would, optionally overlay reference/, and run the hidden test."""
    work = Path(tempfile.mkdtemp(prefix="bench3-validate-")) / "work"
    shutil.copytree(task, work, ignore=shutil.ignore_patterns("reference", "PROMPT.txt", ".import.json"))
    if apply_reference:
        meta = json.loads((task / ".import.json").read_text())
        if meta.get("reference_patch"):
            p = work / "_gold.patch"
            p.write_text((task / "reference" / "gold.patch").read_text())
            sh(["git", "apply", "--whitespace=nowarn", str(p)], cwd=work)
            p.unlink()
        else:
            for f in (task / "reference").rglob("*"):
                if f.is_file():
                    dest = work / f.relative_to(task / "reference")
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(f, dest)
    shutil.move(str(work / "hidden_test.py"), str(work / "_hidden_test.py"))
    r = subprocess.run([sys.executable, "-m", "unittest", "_hidden_test", "-v"], cwd=work,
                       capture_output=True, text=True, timeout=3600)
    shutil.rmtree(work.parent, ignore_errors=True)
    return r.returncode == 0, (r.stdout + r.stderr)[-1500:]


def validate(task: Path) -> dict:
    meta = json.loads((task / ".import.json").read_text())
    fixture_ok, fixture_log = grade_tree(task, apply_reference=False)
    out = {"fails_on_fixture": not fixture_ok}
    if any((task / "reference").rglob("*")):
        ref_ok, ref_log = grade_tree(task, apply_reference=True)
        out["passes_on_reference"] = ref_ok
        if not ref_ok:
            out["reference_log"] = ref_log[-600:]
    else:
        out["passes_on_reference"] = None  # no upstream reference; checked one way only
    out["kept"] = out["fails_on_fixture"] and out["passes_on_reference"] is not False
    meta["validation"] = out
    (task / ".import.json").write_text(json.dumps(meta, indent=1))
    return meta


