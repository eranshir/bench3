def iac_eval(per_band: int, seed: int) -> list[Path]:
    rows = []
    for off in range(0, 458, 100):
        rows += [r["row"] for r in json.load(urllib.request.urlopen(IAC_ROWS % off))["rows"]]
    rng = random.Random("iac-eval:%d" % seed)
    made = []
    for band, levels in (("1-2", {"1", "2"}), ("3-4", {"3", "4"}), ("5-6", {"5", "6"})):
        pool = [i for i, r in enumerate(rows) if str(r["Difficulty"]) in levels]
        for i in rng.sample(pool, min(per_band, len(pool))):
            r = rows[i]
            pkg = re.search(r"^package\s+([\w.]+)", r["Rego intent"], re.M)
            prompt = (r["Prompt"].strip() + "\n\n# Your task\n\nWrite the Terraform configuration in main.tf in the "
                      "current directory, using the AWS provider. It will be checked with terraform plan (no real AWS "
                      "account is used) and with policy checks on the planned resources.")
            spec = {"kind": "terraform", "override": TF_OVERRIDE, "rego": r["Rego intent"],
                    "package": pkg.group(1) if pkg else "terraform.validation",
                    "plugin_cache": str(CACHE / "terraform-plugins"), "timeout": 900}
            meta = {"source": "autoiac-project/iac-eval", "role": "coder-iac", "upstream_id": "row-%d" % i,
                    "resources": r["Resource"], "difficulty_label": band + " (level %s)" % r["Difficulty"],
                    "licence": "MIT (repository)", "imported_at": datetime.now(timezone.utc).isoformat()}
            made.append(write_task("iac-eval", "row-%03d" % i, prompt, lambda task: None, spec,
                                   {"main.tf": r["Reference output"]}, meta))
    return made


