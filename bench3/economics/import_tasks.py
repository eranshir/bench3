#!/usr/bin/env python3
"""Import graded agentic tasks from public sources into bench3's task layout.

Each imported task is a directory under tasks/imported/<family>/<id>/ in the
layout economics/run_agentic.py already runs: PROMPT.txt, the visible fixture,
hidden_test.py (self-contained: test data travel inside it) and reference/.
Nothing upstream is vendored into git: tasks/imported/ is ignored and is
rebuilt from the pinned sources by this script. Only imported_tasks.json, the
manifest of what was imported and how it validated, is committed.

Every grader is checked in both directions before a task is kept: it must
fail on the shipped fixture and pass on the reference solution. Sources with
no reference (code-contests) are checked one way and say so.

usage:
  import_tasks.py polyglot --lang python --count 2 [--seed 0]
  import_tasks.py swe --instance sympy__sympy-12345 [...]
  import_tasks.py swe --sample sympy/sympy --per-difficulty 2 [--seed 0]
  import_tasks.py codecontests --per-band 2 [--seed 0]
  import_tasks.py validate imported/<family>/<id>
"""
